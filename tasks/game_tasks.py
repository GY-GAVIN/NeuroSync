"""
NeuroSync — 三个协作任务定义

知识注入机制：在任务创建时，将 knowledge/game_concepts.py 中的
博弈论概念模板通过 f-string 拼入任务 description，为 Agent 提供框架指导。
"""

from crewai import Task, Agent
from knowledge.game_concepts import KNOWLEDGE_MAP


def create_modeling_task(modeler: Agent, user_input: str) -> Task:
    """任务 1：博弈建模 — Agent 1 将用户情境形式化为博弈模型。"""
    knowledge = "\n\n".join(KNOWLEDGE_MAP["modeler"])

    return Task(
        description=(
            f"## 用户情境\n\n{user_input}\n\n"
            "---\n\n"
            "## 你的任务：将上述情境转化为规范的博弈论模型\n\n"
            "请严格按照以下步骤进行分析：\n\n"
            "### 步骤 1：识别参与者 (Players)\n"
            "- 列出所有相关决策主体（至少 2 个）\n"
            "- 说明每个参与者的目标/效用函数\n"
            "- 如果涉及「自然」或外部不确定性，也请注明\n\n"
            "### 步骤 2：列举策略 (Strategies)\n"
            "- 每个参与者的可选行动集合\n"
            "- 注意区分同时行动和顺序行动\n"
            "- 策略应简洁、互斥、完备\n\n"
            "### 步骤 3：构建收益 (Payoffs)\n"
            "- 使用 build_payoff_matrix 工具构建标准化的收益矩阵\n"
            "- 收益值应反映参与者的真实偏好排序（可用 1-10 或 -5 到 5 标度）\n"
            "- 解释每个收益值的含义：为什么这个结果对应这个数值？\n\n"
            "### 步骤 4：识别博弈类型\n"
            "- 使用 identify_game_type 工具判断博弈的经典分类\n"
            "- 综合讨论：同时/顺序、完全/不完全信息、零和/非零和、一次/重复\n\n"
            "### 步骤 5：陈述假设\n"
            "- 明确列出你在建模过程中所做的所有假设\n"
            "- 例如：理性假设、共同知识假设、收益可比较性等\n"
            "- 讨论如果假设不成立，模型会如何变化\n\n"
            "---\n\n"
            f"## 参考理论框架\n\n{knowledge}\n\n"
            "---\n\n"
            "## 输出要求\n\n"
            "请输出包含以下部分的分析：\n"
            "1. **参与者和策略**的清晰描述\n"
            "2. 通过 build_payoff_matrix 工具构建的**收益矩阵**（JSON 格式）\n"
            "3. **博弈类型**分类及理由\n"
            "4. **模型假设**清单\n"
            "5. 一段**叙述性总结**，用通俗语言解释该博弈的本质"
        ),
        expected_output=(
            "完整的博弈模型，包含 Players、Strategies、"
            "Payoff Matrix（JSON 格式）、Game Type、Assumptions、"
            "以及通俗叙述。收益矩阵必须通过 build_payoff_matrix 工具输出。"
        ),
        agent=modeler,
    )


def create_analysis_task(analyst: Agent, user_input: str) -> Task:
    """任务 2：均衡分析 — Agent 2 对博弈模型进行均衡求解。"""
    knowledge = "\n\n".join(KNOWLEDGE_MAP["analyst"])

    return Task(
        description=(
            f"## 用户情境（参考）\n\n{user_input}\n\n"
            "---\n\n"
            "## 你的任务：对博弈模型进行全面的均衡分析\n\n"
            "请严格按照以下步骤进行分析 —— 每个步骤必须使用对应的工具：\n\n"
            "### 步骤 1：纯策略 Nash 均衡\n"
            "- 使用 solve_pure_nash 工具计算纯策略 Nash 均衡\n"
            "- 解释每个均衡的含义：为什么这个策略组合是稳定的？\n"
            "- 如果没有纯策略均衡，明确说明\n\n"
            "### 步骤 2：占优策略分析\n"
            "- 使用 check_dominance 工具识别严格/弱占优和劣策略\n"
            "- 如果有严格占优策略，强调这是最稳健的预测\n"
            "- 如果有劣策略，说明可以通过迭代剔除来简化博弈\n\n"
            "### 步骤 3：混合策略均衡（如适用）\n"
            "- 如果純策略 Nash 均衡不存在，使用 solve_mixed_nash 工具\n"
            "- 解释混合策略的现实含义：不是「随机选择」，而是「不可预测」\n"
            "- 注意：该工具仅支持 2×2 博弈，其他情况请自行推导\n\n"
            "### 步骤 4：Pareto 分析\n"
            "- 使用 pareto_analysis 工具识别 Pareto 最优结果\n"
            "- 指出是否存在 Pareto 改进机会\n"
            "- 讨论效率与公平的权衡\n\n"
            "### 步骤 5：子博弈完美均衡（顺序博弈）\n"
            "- 如果模型是顺序博弈，使用逆向归纳法求解 SPNE\n"
            "- 注意区分可置信威胁和不可置信威胁\n\n"
            "### 步骤 6：综合解读\n"
            "- 哪些均衡是最可信的预测？为什么？\n"
            "- 是否存在多重均衡问题？如果有，如何选择？\n"
            "- 这个博弈的「策略本质」是什么？\n\n"
            "---\n\n"
            f"## 参考理论框架\n\n{knowledge}\n\n"
            "---\n\n"
            "## 输出要求\n\n"
            "请输出包含以下部分的分析：\n"
            "1. 每个计算工具的**输出结果**及你的**解读**\n"
            "2. 纯策略均衡列表（如有）\n"
            "3. 混合策略均衡（如有）\n"
            "4. 占优关系和 Pareto 分析\n"
            "5. **综合解读**：用通俗语言告诉非专业用户这些均衡意味着什么"
        ),
        expected_output=(
            "全面的均衡分析报告，包含纯策略/混合策略 Nash 均衡列表、"
            "占优策略分析、Pareto 前沿面、综合解读。"
            "必须使用 solve_pure_nash 等工具进行计算。"
        ),
        agent=analyst,
    )


def create_advice_task(advisor: Agent, user_input: str) -> Task:
    """任务 3：策略建议 — Agent 3 给出可执行的行动建议。"""
    knowledge = "\n\n".join(KNOWLEDGE_MAP["advisor"])

    return Task(
        description=(
            f"## 用户情境（参考）\n\n{user_input}\n\n"
            "---\n\n"
            "## 你的任务：将博弈论分析转化为可执行的策略建议\n\n"
            "请基于前序的建模和均衡分析结果，给出以下建议：\n\n"
            "### 步骤 1：核心策略建议\n"
            "- 用户在当前博弈中应该选择什么行动？为什么？\n"
            "- 说明此建议在什么条件下成立（假设敏感性分析）\n"
            "- 给出一句话的「底线建议」\n\n"
            "### 步骤 2：行为因素考量\n"
            "- 考虑真实人类可能偏离理性均衡的方式：\n"
            "  * 公平偏好：对方会不会因为觉得不公平而报复？\n"
            "  * 互惠性：善意是否会得到善意回应？\n"
            "  * 过度自信：用户或对方是否可能高估自己的优势？\n"
            "  * 损失厌恶：对损失的恐惧是否会扭曲决策？\n\n"
            "### 步骤 3：承诺与信号\n"
            "- 用户可以通过什么方式改变博弈结构？\n"
            "  * 可置信的承诺：烧桥 / 签合同 / 公开承诺\n"
            "  * 信号传递：如何让对方相信你的意图？\n"
            "  * 不可置信的威胁：什么威胁对方不会当真？\n\n"
            "### 步骤 4：重复博弈视角\n"
            "- 如果这是长期关系（或可以转化为长期关系），建议如何变化？\n"
            "- Tit-for-Tat / Grim Trigger 等策略的适用性\n"
            "- 声誉机制的影响\n\n"
            "### 步骤 5：BATNA 分析\n"
            "- 用户的最佳替代方案是什么？\n"
            "- 如何提高自己的 BATNA？\n"
            "- BATNA 如何影响谈判地位？\n\n"
            "### 步骤 6：行动计划\n"
            "- 列出 3-5 条具体、可执行的行动\n"
            "- 每条行动标注预期效果和风险\n"
            "- 按优先级排序\n\n"
            "---\n\n"
            f"## 参考理论框架\n\n{knowledge}\n\n"
            "---\n\n"
            "## 输出要求\n\n"
            "请输出一份可以直接用于决策的策略建议，包含：\n"
            "1. 核心建议（一句话 + 详细说明）\n"
            "2. 行为因素分析\n"
            "3. 承诺与信号策略\n"
            "4. 重复博弈视角（如适用）\n"
            "5. BATNA 分析\n"
            "6. 按优先级排序的行动计划"
        ),
        expected_output=(
            "一份可直接用于决策的策略建议报告，包含核心建议、"
            "行为因素分析、承诺与信号、重复博弈视角、BATNA 分析、"
            "以及具体的行动计划。语言通俗、建议可执行。"
        ),
        agent=advisor,
    )
